"""Generate the writing-spark triggers, effects and localization.

A spark is one variable per writing form, kehillah_spark_<form>, holding its
tier: 1 Insight, 2 Chiddush, 3 Great Work. Scholarly actions grant sparks from
a named pool; Write a Sefer offers only forms the author holds a spark for, and
starting a project uses that spark up. See
docs/spec/2026-11-23-writing-sparks.md.
"""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TRIGGERS = ROOT / "common/scripted_triggers/kehillah_writing_spark_generated_triggers.txt"
EFFECTS = ROOT / "common/scripted_effects/kehillah_writing_spark_generated_effects.txt"
LOC = ROOT / "localization/english/kehillah_writing_spark_generated_l_english.yml"
LANDMARK_STATUS = ROOT / "common/scripted_triggers/kehillah_writing_landmark_generated_triggers.txt"

# form: (discipline, aptitude key, noun phrase)
FORMS = {
    "torah": ("parshanut", "parshanut", "a Torah commentary"),
    "midrash": ("parshanut", "parshanut", "a midrashic exposition"),
    "poetry": ("parshanut", "parshanut", "a cycle of sacred poems"),
    "grammar": ("parshanut", "parshanut", "a grammar of Scripture's language"),
    "chronicle": ("parshanut", "parshanut", "a chronicle of our people"),
    "talmud": ("talmudics", "talmudics", "a Talmud commentary"),
    "yerushalmi": ("talmudics", "talmudics", "a Yerushalmi commentary"),
    "law": ("talmudics", "talmudics", "a halakhic treatise"),
    "responsa": ("talmudics", "talmudics", "a collection of responsa"),
    "minhag": ("talmudics", "talmudics", "a book of customs"),
    "siddur": ("talmudics", "talmudics", "an order of prayer"),
    "tradition_history": ("talmudics", "talmudics", "a chain of the sages"),
    "scriptural_law": ("talmudics", "talmudics", "a book of Scripture's commandments"),
    "dialogue": ("hashkafa", "machshava", "a dialogue on Scripture and law"),
    "systematic_dialogue": ("hashkafa", "machshava", "a dialogue on faith and reason"),
    "mystical": ("hashkafa", "machshava", "a work on the hidden structure of creation"),
    "disputation": ("hashkafa", "machshava", "a disputation for our tradition"),
    "translation": ("hashkafa", "machshava", "a glossed translation"),
    "ethics": ("hashkafa", "machshava", "an exhortation on righteous conduct"),
    "devotion": ("hashkafa", "machshava", "a work on the duties of the heart"),
}

# Which forms each kind of scholarly action can spark.
POOLS = {
    "study_parshanut": ["torah", "midrash", "poetry", "grammar", "chronicle"],
    "study_talmudics": ["talmud", "yerushalmi", "law", "minhag", "siddur", "tradition_history", "scriptural_law"],
    "study_hashkafa": ["dialogue", "systematic_dialogue", "mystical", "disputation", "translation", "ethics", "devotion"],
    "court": ["law", "responsa", "minhag", "scriptural_law"],
    "letters": ["responsa", "law"],
    "sermon": ["torah", "midrash", "poetry", "ethics", "devotion"],
    "debate": ["disputation", "dialogue", "systematic_dialogue", "tradition_history"],
    "any": list(FORMS),
}

# Who may receive a spark in a form: the former project gate, so language,
# source, rite and date stay part of the idea. Answering a she'elah replaces
# the responsa gate's Bet Din memory.
HOLD_GATE = {form: f"kehillah_writing_{form}_trigger = yes" for form in FORMS}
HOLD_GATE["responsa"] = "kehillah_writing_law_trigger = yes"

HEADER = "# Generated by scripts/kehillah_writing_sparks.py. Do not edit by hand.\n"


def landmark_forms() -> set[str]:
    text = LANDMARK_STATUS.read_text(encoding="utf-8-sig")
    return {form for form in FORMS if f"kehillah_writing_landmark_has_{form}_trigger = {{ always = yes }}" in text}


def triggers() -> str:
    out = [HEADER]
    for form in FORMS:
        out.append(f"kehillah_spark_can_hold_{form}_trigger = {{ {HOLD_GATE[form]} }}")
        out.append(f"kehillah_spark_can_gain_{form}_trigger = {{ NOT = {{ has_variable = kehillah_spark_{form} }} kehillah_spark_can_hold_{form}_trigger = yes }}")
    out.append("")
    for discipline in ("parshanut", "talmudics", "hashkafa"):
        held = " ".join(f"has_variable = kehillah_spark_{f}" for f, d in FORMS.items() if d[0] == discipline)
        out.append(f"kehillah_has_spark_{discipline}_trigger = {{ OR = {{ {held} }} }}")
    held = " ".join(f"has_variable = kehillah_spark_{f}" for f in FORMS)
    out.append(f"kehillah_has_any_spark_trigger = {{ OR = {{ {held} }} }}")
    out.append("")
    for pool, forms in POOLS.items():
        gain = " ".join(f"kehillah_spark_can_gain_{f}_trigger = yes" for f in forms)
        out.append(f"kehillah_spark_pool_{pool}_open_trigger = {{ OR = {{ {gain} }} }}")
    return "\n".join(out) + "\n"


def effects(landmarks: set[str]) -> str:
    out = [HEADER]
    out.append("# Scope: a writer. Grants one new spark in FORM, then lets held sparks ripen.")
    for form, (_, apt, _) in FORMS.items():
        out += [
            f"kehillah_spark_grant_{form}_effect = {{",
            "\tif = {",
            f"\t\tlimit = {{ kehillah_spark_can_gain_{form}_trigger = yes }}",
            f"\t\tset_variable = {{ name = kehillah_spark_{form} value = 1 }}",
            "\t\tif = {",
            "\t\t\tlimit = { is_ai = no }",
            f"\t\t\tsend_interface_toast = {{ type = event_toast_text_good title = kehillah_spark_new_toast_t desc = kehillah_spark_new_{form} left_icon = this }}",
            "\t\t}",
            "\t}",
            "}",
        ]
    out.append("")
    out.append("# A held spark deepens when its next rung is met. Insight to Chiddush:")
    out.append("# discipline aptitude. Chiddush to Great Work: a landmark niche's conditions.")
    for form, (_, apt, _) in FORMS.items():
        lines = [
            f"kehillah_spark_ripen_{form}_effect = {{",
            "\tif = {",
            f"\t\tlimit = {{ var:kehillah_spark_{form} ?= 1 kehillah_writing_{apt}_aptitude_value >= kehillah_spark_deepen_aptitude_value }}",
            f"\t\tset_variable = {{ name = kehillah_spark_{form} value = 2 }}",
            f"\t\tif = {{ limit = {{ is_ai = no }} send_interface_toast = {{ type = event_toast_text_good title = kehillah_spark_deepen_toast_t desc = kehillah_spark_deepen_{form} left_icon = this }} }}",
            "\t}",
        ]
        if form in landmarks:
            lines += [
                "\tif = {",
                f"\t\tlimit = {{ var:kehillah_spark_{form} ?= 2 kehillah_writing_landmark_ready_{form}_trigger = yes }}",
                f"\t\tset_variable = {{ name = kehillah_spark_{form} value = 3 }}",
                f"\t\tif = {{ limit = {{ is_ai = no }} send_interface_toast = {{ type = event_toast_text_good title = kehillah_spark_great_toast_t desc = kehillah_spark_great_{form} left_icon = this }} }}",
                "\t}",
            ]
        lines.append("}")
        out += lines
    out.append("")
    out.append("kehillah_spark_ripen_all_effect = {")
    for form in FORMS:
        out.append(f"\tif = {{ limit = {{ has_variable = kehillah_spark_{form} }} kehillah_spark_ripen_{form}_effect = yes }}")
    out.append("}")
    out.append("")
    out.append("# Scope: a writer. One new spark from the pool, if any is open.")
    for pool, forms in POOLS.items():
        out += [
            f"kehillah_spark_from_{pool}_effect = {{",
            "\tif = {",
            f"\t\tlimit = {{ kehillah_sefer_can_write_trigger = yes kehillah_spark_pool_{pool}_open_trigger = yes }}",
            "\t\trandom_list = {",
        ]
        for f in forms:
            out.append(f"\t\t\t10 = {{ trigger = {{ kehillah_spark_can_gain_{f}_trigger = yes }} kehillah_spark_grant_{f}_effect = yes }}")
        out += ["\t\t}", "\t}", "\tkehillah_spark_ripen_all_effect = yes", "}"]
    out.append("")
    out.append("# Scope: the author starting a project. Uses up the chosen form's spark.")
    out.append("kehillah_spark_consume_current_effect = {")
    first = True
    for form in FORMS:
        kw = "if" if first else "else_if"
        first = False
        out.append(f"\t{kw} = {{ limit = {{ var:kehillah_writing_form ?= flag:{form} }} remove_variable = kehillah_spark_{form} }}")
    out.append("}")
    return "\n".join(out) + "\n"


def loc() -> str:
    out = ["l_english:"]
    for form, (_, _, noun) in FORMS.items():
        out.append(f' kehillah_spark_form_{form}:0 "{noun}"')
        out.append(f' kehillah_spark_new_{form}:0 "An idea for $kehillah_spark_form_{form}$ has taken hold. #weak Write a Sefer can now develop it.#!"')
        out.append(f' kehillah_spark_deepen_{form}:0 "My idea for $kehillah_spark_form_{form}$ has deepened into a Chiddush."')
        out.append(f' kehillah_spark_great_{form}:0 "My idea for $kehillah_spark_form_{form}$ could become a work that endures."')
    return "﻿" + "\n".join(out) + "\n"


def main() -> None:
    TRIGGERS.write_text("﻿" + triggers(), encoding="utf-8", newline="\n")
    EFFECTS.write_text("﻿" + effects(landmark_forms()), encoding="utf-8", newline="\n")
    LOC.write_text(loc(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
