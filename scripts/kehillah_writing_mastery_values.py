"""Generate writing aptitude counts from the existing stable work catalog."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
WORKS = json.loads((ROOT / "scripts/kehillah_library_catalog.json").read_text(encoding="utf-8"))["works"]
OUTPUT = ROOT / "common/script_values/kehillah_writing_mastery_values.txt"


def main() -> None:
    lines = ["# Generated by scripts/kehillah_writing_mastery_values.py."]
    for genre, value_name in (
        ("parshanut", "kehillah_writing_parshanut_mastered_value"),
        ("talmudics", "kehillah_writing_other_talmudics_mastered_value"),
        ("hashkafa", "kehillah_writing_machshava_mastered_value"),
    ):
        lines += ["", f"{value_name} = {{", "\tvalue = 0"]
        for key, work in WORKS.items():
            if key.startswith("work_authored_"):
                genre_id = {"parshanut": 1, "talmudics": 2, "hashkafa": 3}[genre]
                condition = (
                    f"is_target_in_variable_list = {{ name = kehillah_mastered_works target = flag:{key} }} "
                    f"exists = global_var:kehillah_wk_{key}_genre "
                    f"global_var:kehillah_wk_{key}_genre = {genre_id}"
                )
            elif work.get("genre") == genre:
                if genre == "talmudics" and (
                    key.startswith("work_bavli_") or key.startswith("work_yerushalmi_")
                ):
                    continue  # already counted by the corpus values
                condition = f"is_target_in_variable_list = {{ name = kehillah_mastered_works target = flag:{key} }}"
            else:
                continue
            lines.append(f"\tif = {{ limit = {{ {condition} }} add = 1 }}")
        lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")


if __name__ == "__main__":
    main()
