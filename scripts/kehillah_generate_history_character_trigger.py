"""Generate common/scripted_triggers/kehillah_history_character_triggers.txt.

The trigger kehillah_is_history_file_character_trigger is true for every
character defined in this mod's history/characters/*.txt. Game start uses it
to leave authored (historical) characters alone when it hands out Kohen and
Levite to unnamed Jewish men. Re-run after adding or removing a history file:

    python scripts/kehillah_generate_history_character_trigger.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HISTORY = ROOT / "history" / "characters"
OUT = ROOT / "common" / "scripted_triggers" / "kehillah_history_character_triggers.txt"

KEY = re.compile(r"^(\S+) = \{", re.MULTILINE)

ids = []
for path in sorted(HISTORY.glob("*.txt")):
    text = path.read_text(encoding="utf-8-sig")
    for key in KEY.findall(text):
        if key not in ids:
            ids.append(key)

lines = [
    "# GENERATED by scripts/kehillah_generate_history_character_trigger.py. Do not edit by hand.",
    "# True for every character authored in this mod's history/characters files.",
    "# Scope: character. Does not know vanilla's own history characters.",
    "kehillah_is_history_file_character_trigger = {",
    "\tOR = {",
]
lines += [f"\t\tthis = character:{key}" for key in ids]
lines += ["\t}", "}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(ids)} characters -> {OUT}")
