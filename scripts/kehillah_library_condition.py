"""Generate the per-work lists for sefer condition (wear, repair, genizah).

Run from the repository root:  python scripts/kehillah_library_condition.py

ADDED 2026-11-24 (Daniel: "Can we make sefarim deteriorate over time? So you
need to buy new ones or pay to repair them? If they break they go to the
genizah"). Design and build record:
docs/implementation/2026-11-24-sefer-condition-and-genizah.md.

Kept apart from scripts/kehillah_library_catalog.py on purpose: it reads the
same catalog (scripts/kehillah_library_catalog.json) but writes only its own
files, so the two generators never overwrite each other's output. Add a work
to the catalog, then run both.

Outputs:
  common/script_values/kehillah_library_condition_generated_values.txt
      kehillah_lib_condition_<flag> (library title scope): 0 sound, 1 worn,
      2 fragile. The GUI reads it by flag name.
  common/scripted_effects/kehillah_library_condition_generated_effects.txt
      kehillah_lib_wear_yearly_effect (library title scope): the yearly wear
      roll for every held work, the AI's repair of fragile works, and the
      cleanup of condition entries for works no longer held.
  common/scripted_guis/kehillah_library_condition_gui.txt
      kehillah_lib_repair_<flag>: the Repair button (scope:library).
  common/customizable_localization/kehillah_library_condition_custom_loc.txt
      KehillahWearWorkName: the work in var kehillah_wear_work_loc.

The Tanakh never wears: every Jewish library keeps it and the yearly pass
re-seeds it (kehillah_lib_seed_tanakh_effect), so wear on it would be noise.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "scripts" / "kehillah_library_catalog.json"
VALUES = ROOT / "common/script_values/kehillah_library_condition_generated_values.txt"
EFFECTS = ROOT / "common/scripted_effects/kehillah_library_condition_generated_effects.txt"
GUI = ROOT / "common/scripted_guis/kehillah_library_condition_gui.txt"
CUSTOM_LOC = ROOT / "common/customizable_localization/kehillah_library_condition_custom_loc.txt"

BOM = "﻿"
HEADER = [
    "# GENERATED by scripts/kehillah_library_condition.py from",
    "# scripts/kehillah_library_catalog.json -- edit the catalog or the script, not this file.",
]


def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(BOM + "\r\n".join(lines) + "\r\n", encoding="utf-8", newline="")


def wears(w):
    return w.get("corpus") != "tanakh"


def in_list(f, lst):
    return f"is_target_in_variable_list = {{ name = {lst} target = flag:{f} }}"


def write_values(order, works):
    out = HEADER + [
        "# Library title scope. 0 sound, 1 worn, 2 fragile.",
    ]
    for f in order:
        out.append("")
        if not wears(works[f]):
            out.append(f"kehillah_lib_condition_{f} = {{ value = 0 }}")
            continue
        out += [
            f"kehillah_lib_condition_{f} = {{",
            "\tvalue = 0",
            f"\tif = {{ limit = {{ {in_list(f, 'kehillah_library_worn')} }} value = 1 }}",
            f"\telse_if = {{ limit = {{ {in_list(f, 'kehillah_library_fragile')} }} value = 2 }}",
            "}",
        ]
    write(VALUES, out)


def write_effects(order, works):
    out = HEADER + [
        "",
        "# Library title scope, once a year from kehillah_lib_yearly_library_effect.",
        "# A held work: an AI holder first mends it if it is fragile and he can",
        "# spare the gold, then it rolls for wear. A work no longer held (lost to a",
        "# cherem, a seizure or a sale) drops any condition it had, so a new copy",
        "# arrives sound.",
        "kehillah_lib_wear_yearly_effect = {",
    ]
    for f in order:
        if not wears(works[f]):
            continue
        out += [
            "\tif = {",
            f"\t\tlimit = {{ {in_list(f, 'kehillah_library_works')} }}",
            "\t\tif = {",
            "\t\t\tlimit = {",
            f"\t\t\t\t{in_list(f, 'kehillah_library_fragile')}",
            "\t\t\t\tkehillah_lib_ai_will_repair_trigger = yes",
            "\t\t\t}",
            f"\t\t\tkehillah_lib_pay_and_repair_effect = {{ WORK = flag:{f} }}",
            "\t\t}",
            "\t\trandom = {",
            "\t\t\tchance = kehillah_lib_wear_chance_value",
            f"\t\t\tkehillah_lib_wear_step_effect = {{ WORK = flag:{f} }}",
            "\t\t}",
            "\t}",
            "\telse_if = {",
            "\t\tlimit = {",
            "\t\t\tOR = {",
            f"\t\t\t\t{in_list(f, 'kehillah_library_worn')}",
            f"\t\t\t\t{in_list(f, 'kehillah_library_fragile')}",
            "\t\t\t}",
            "\t\t}",
            f"\t\tremove_list_variable = {{ name = kehillah_library_worn target = flag:{f} }}",
            f"\t\tremove_list_variable = {{ name = kehillah_library_fragile target = flag:{f} }}",
            "\t}",
        ]
    out.append("}")
    write(EFFECTS, out)


def write_gui(order, works):
    out = HEADER + [
        "# The Repair button on a book's page. The shelf's library goes along as",
        "# scope:library; only its holder may pay to mend its books.",
    ]
    for f in order:
        if not wears(works[f]):
            # The book page asks for every work's button by name; a missing
            # scripted gui would flood error.log on the Tanakh's page.
            out += [
                "",
                f"kehillah_lib_repair_{f} = {{",
                "\tscope = character",
                "\tis_shown = { always = no }",
                "}",
            ]
            continue
        out += [
            "",
            f"kehillah_lib_repair_{f} = {{",
            "\tscope = character",
            "\tsaved_scopes = { library }",
            "\tis_shown = {",
            "\t\tscope:library ?= {",
            "\t\t\tholder ?= root",
            "\t\t\tOR = {",
            f"\t\t\t\t{in_list(f, 'kehillah_library_worn')}",
            f"\t\t\t\t{in_list(f, 'kehillah_library_fragile')}",
            "\t\t\t}",
            "\t\t}",
            "\t}",
            "\tis_valid = {",
            f"\t\tkehillah_lib_can_afford_repair_trigger = {{ WORK = flag:{f} }}",
            "\t}",
            "\teffect = {",
            f"\t\tscope:library = {{ kehillah_lib_pay_and_repair_effect = {{ WORK = flag:{f} }} }}",
            "\t}",
            "}",
        ]
    write(GUI, out)


def write_custom_loc(order):
    out = HEADER + ["KehillahWearWorkName = {", "\ttype = character"]
    for f in order:
        out += [
            "\ttext = {",
            "\t\ttrigger = {",
            "\t\t\thas_variable = kehillah_wear_work_loc",
            f"\t\t\tvar:kehillah_wear_work_loc = flag:{f}",
            "\t\t}",
            f"\t\tlocalization_key = kehillah_lib_name_{f}",
            "\t}",
        ]
    out += [
        "\ttext = {",
        "\t\tfallback = yes",
        "\t\tlocalization_key = KEHILLAH_LIB_COMMISSION_UNKNOWN_WORK",
        "\t}",
        "}",
    ]
    write(CUSTOM_LOC, out)


def main():
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    order, works = data["order"], data["works"]
    write_values(order, works)
    write_effects(order, works)
    write_gui(order, works)
    write_custom_loc(order)
    print(f"{len(order)} works; {sum(1 for f in order if wears(works[f]))} can wear")


if __name__ == "__main__":
    main()
