def extract(path, eid):
    text = open(os.path.join(GAME, path), encoding="utf-8-sig").read().replace("\r\n", "\n")
    lines = text.split("\n")
    namespace = next(l.strip() for l in lines if l.startswith("namespace"))
    start = next(i for i, l in enumerate(lines) if l.startswith(eid + " = {"))
    end = next(i for i in range(start + 1, len(lines)) if lines[i].rstrip() == "}")
    return namespace, lines[start:end + 1]


def extract_local_effect(path, name):
    """A `scripted_effect x = {...}` defined inside a vanilla event file is
    visible only in that file, so an override that calls it needs a copy."""
    _, body = extract(path, "scripted_effect " + name)
    return "\n".join(body)


# Vanilla file-local scripted effects the copied events call.
LOCAL_EFFECTS = {
    "host_dinner_events.3020": ["3020_drinking_duel_effect"],
}


def build(eid, body, opt):
    body = list(body)
    body.insert(1, "\tid_override_priority = 10 # Jewish Communities: outrank vanilla (0)")
    # Options must come before an `after` block if there is one.
    at = next((i for i, l in enumerate(body) if l.rstrip() == "\tafter = {"), len(body) - 1)
    while at > 0 and body[at - 1].strip() == "":
        at -= 1
    body[at:at] = opt.split("\n")
    return "\n".join(body)


for target in TARGETS:
    namespaces, chunks = [], []
    for path, eid, offerer, effects, *rest in target["events"]:
        ns, body = extract(path, eid)
        if ns not in namespaces:
            namespaces.append(ns)
        local = "".join(f"# Vanilla file-local effect, copied from {path}\n{extract_local_effect(path, n)}\n\n"
                        for n in LOCAL_EFFECTS.get(eid, []))
        chunks.append(local + f"# Vanilla: {path}\n" + build(eid, body, option(eid, offerer, effects, *rest)))
    out = os.path.join(MOD, target["out"])
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(namespaces="\n".join(namespaces)) + "\n" + "\n\n".join(chunks) + "\n")
    print("wrote", target["out"])
