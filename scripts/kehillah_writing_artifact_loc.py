"""Generate stable artifact-name dispatch from the existing Sefer catalog."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "scripts" / "kehillah_library_catalog.json"
OUTPUT = ROOT / "common" / "customizable_localization" / "kehillah_writing_artifact_custom_loc.txt"
REFS_OUTPUT = ROOT / "common" / "scripted_effects" / "kehillah_writing_artifact_refs_effects.txt"
IDENTITY_OUTPUT = ROOT / "common" / "scripted_effects" / "kehillah_writing_landmark_artifact_generated_effects.txt"
IDENTITY_LOC = ROOT / "localization" / "english" / "kehillah_writing_landmark_artifact_l_english.yml"


def main() -> None:
    works = json.loads(CATALOG.read_text(encoding="utf-8"))["works"]
    keys = [
        key for key, work in works.items()
        if work.get("year", 0) > 867 or key.startswith("work_authored_")
    ]
    lines = [
        "# Generated by scripts/kehillah_writing_artifact_loc.py.",
        "# The artifact keeps its own work ID through inheritance and later books.",
        "KehillahWritingArtifactName = {",
        "\ttype = artifact",
    ]
    for key in keys:
        lines.extend([
            "\ttext = {",
            f"\t\ttrigger = {{ var:kehillah_artifact_work ?= flag:{key} }}",
            f"\t\tlocalization_key = kehillah_lib_name_{key}",
            "\t}",
        ])
    lines.extend([
        "\ttext = {",
        "\t\ttrigger = { always = no }",
        "\t\tlocalization_key = kehillah_writing_unknown_manuscript",
        "\t\tfallback = yes",
        "\t}",
        "}",
    ])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")
    refs = [
        "# Generated by scripts/kehillah_writing_artifact_loc.py.",
        "# Artifact scope. A surviving original manuscript protects its authored slot.",
        "kehillah_writing_register_manuscript_effect = {",
    ]
    for key in keys:
        if not key.startswith("work_authored_"):
            continue
        refs.extend([
            "\tif = {",
            f"\t\tlimit = {{ var:kehillah_artifact_work ?= flag:{key} }}",
            f"\t\tset_global_variable = {{ name = kehillah_wk_{key}_manuscript value = this }}",
            "\t}",
        ])
    refs.append("}")
    REFS_OUTPUT.write_text("\n".join(refs) + "\n", encoding="utf-8-sig")
    identity = ["# Generated by scripts/kehillah_writing_artifact_loc.py.",
                "# Scope: new artifact. Use a direct per-work localization key.",
                "kehillah_writing_set_landmark_artifact_identity_effect = {"]
    identity_loc = ["l_english:"]
    future = [key for key in keys if not key.startswith("work_authored_")]
    for index, key in enumerate(future):
        if key == "work_rashi_torah":
            title_key = "kehillah_writing_rashi_torah_dynamic"
        elif key == "work_rashi_talmud":
            title_key = "kehillah_writing_rashi_talmud_dynamic"
        elif works[key].get("writing_title"):
            title_key = f"kehillah_future_title_{key}_written"
        else:
            title_key = f"kehillah_lib_name_{key}"
        identity += [f"\t{'if' if index == 0 else 'else_if'} = {{",
                     f"\t\tlimit = {{ root = {{ var:kehillah_sefer_my_latest_work ?= flag:{key} }} }}",
                     f"\t\tset_artifact_name = {title_key}",
                     f"\t\tset_artifact_description = kehillah_writing_landmark_artifact_desc_{key}", "\t}"]
        identity_loc.append(f' kehillah_writing_landmark_artifact_desc_{key}:0 "The original manuscript of ${title_key}$, a landmark work of scholarship. Copies may travel far beyond its first library."')
    identity.append("}")
    IDENTITY_OUTPUT.write_text("\n".join(identity) + "\n", encoding="utf-8-sig")
    IDENTITY_LOC.write_text("\n".join(identity_loc) + "\n", encoding="utf-8-sig")


if __name__ == "__main__":
    main()
