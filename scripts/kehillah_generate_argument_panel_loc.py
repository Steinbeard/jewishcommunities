"""Generate case-specific panel choice names and cited-work names."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "common/customizable_localization/kehillah_din_citation_custom_loc.txt"
OUTPUT = ROOT / "common/customizable_localization/kehillah_din_argument_panel_custom_loc.txt"


def choice_loc(name, variable):
    lines = [f"{name} = {{", "\ttype = character"]
    for n in range(15, 115):
        for position, letter in enumerate("abc", 1):
            lines += [
                "\ttext = {",
                f"\t\ttrigger = {{ involved_activity ?= {{ var:kehillah_din_case = {n} var:{variable} = {position} }} }}",
                f"\t\tlocalization_key = kehillah_bet_din.0{n}1.{letter}",
                "\t}",
            ]
    lines += ["\ttext = { trigger = { always = yes } localization_key = kehillah_din_argument_unrecorded }", "}"]
    return "\n".join(lines)


def source_loc(name, variable, original):
    return original.replace("KehillahDinCiteGrounded", name, 1).replace(
        "kehillah_din_cite_grounded", variable
    ).replace("localization_key = KEHILLAH_LIB_COMMISSION_UNKNOWN_WORK",
              "localization_key = kehillah_din_argument_no_work")


def result_loc(name, variable):
    return f"""{name} = {{
\ttype = character
\ttext = {{ trigger = {{ involved_activity ?= {{ var:{variable} = 1 }} }} localization_key = kehillah_din_argument_held }}
\ttext = {{ trigger = {{ always = yes }} localization_key = kehillah_din_argument_failed }}
}}"""


def generate():
    catalog = CATALOG.read_text(encoding="utf-8-sig")
    start = catalog.index("KehillahDinCiteGrounded = {")
    end = catalog.index("KehillahDinCiteInnovative = {")
    source = catalog[start:end].strip()
    parts = ["# Generated by scripts/kehillah_generate_argument_panel_loc.py."]
    for seat in range(1, 4):
        parts.append(choice_loc(f"KehillahDinVote{seat}Position", f"kehillah_din_vote_{seat}_position"))
        parts.append(source_loc(f"KehillahDinVote{seat}Source", f"kehillah_din_vote_{seat}_cited", source))
        parts.append(result_loc(f"KehillahDinVote{seat}Result", f"kehillah_din_vote_{seat}_success"))
    parts.append(choice_loc("KehillahDinPanelWinner", "kehillah_din_panel_winner"))
    OUTPUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8-sig", newline="\r\n")


if __name__ == "__main__":
    generate()
