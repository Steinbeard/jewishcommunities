"""Build scope-based synod reform. No tenet catalogue: enumerate known tenets.

TENET_INDEX is used only to decode existing book-controversy agenda ordinals.
See docs/spec/2026-11-26-synod-consolidation.md. Run from the repository root.
"""
from pathlib import Path
from kehillah_library_catalog import TENET_INDEX

ROOT = Path(__file__).resolve().parents[1]


def write(path, body, loc=False):
    header = 'l_english:\n' if loc else '# GENERATED by scripts/kehillah_reform_build.py; edit the generator.\n'
    text = '\n'.join(line.rstrip() for line in (header + body.strip()).splitlines()) + '\n'
    (ROOT / path).write_bytes(('\ufeff' + text.replace('\n', '\r\n')).encode('utf-8'))


