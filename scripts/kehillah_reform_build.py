"""Generate the tenet-reform motions (2026-11-08, Sefer redesign follow-up).

Run from the repository root:  python scripts/kehillah_reform_build.py

A Synod or Sanhedrin (V45/V46, the Bet Din's third matter) may take up "a
question of belief": raise a tenet to a core tenet of the host's rite in place
of another, or change its status in the faith -- permit it, ban it, or lift a
ban. Book ceilings follow at once (kehillah_standing_refresh_ceilings_rite_
effect). A Machloket's outcome queues the question on its book's tenet for the
rite's next gathering. Design: docs/spec/2026-11-08-sefer-system-redesign.md,
"Tenet reform" addendum; build record: docs/implementation/2026-11-08-sefer-
redesign-build.md section 8.

Writes:
  common/scripted_triggers/kehillah_reform_triggers.txt
  common/scripted_effects/kehillah_reform_effects.txt
  common/customizable_localization/kehillah_reform_custom_loc.txt
  events/kehillah_reform_events.txt
The motion targets must match TENET_INDEX in kehillah_library_catalog.py
(the same 1..12 indices books use).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOM = "﻿"
HEADER = [
    "# GENERATED by scripts/kehillah_reform_build.py -- edit the script, not this file.",
    "# The tenet-reform loop of the Sefer redesign (2026-11-08).",
]

# (key, loc name) -- indices 1..12 are motion targets (TENET_INDEX order).
TARGETS = [
    ("tenet_talmud_torah", "Talmud Torah"),
    ("tenet_baalei_hamiqra", "Ba'alei ha-Miqra"),
    ("tenet_kehillah_hokhmah", "Hokhmah"),
    ("tenet_kehillah_emunah_temimah", "Emunah Temimah"),
    ("tenet_kehillah_pesak", "Pesak"),
    ("tenet_kehillah_pilpul", "Pilpul"),
    ("tenet_kehillah_geonut", "Ge'onut"),
    ("tenet_kehillah_minhag_avoteinu", "Minhag Avoteinu"),
    ("tenet_kehillah_avelei_tziyon", "Avelei Tziyon"),
    ("tenet_esotericism", "Kabbalah"),
    ("tenet_asceticism", "Hasidut"),
    ("tenet_kehillah_kiddush_hashem", "Kiddush ha-Shem"),
]
# Core tenets a reform may replace: the targets plus vanilla Jewish cores.
REPLACEABLE = TARGETS + [
    ("tenet_legalism", "Legalism"),
    ("tenet_religious_legal_pronouncements", "Halakha"),
    ("tenet_communal_identity", "Communal Identity"),
    ("tenet_inner_journey", "Inner Journey"),
    ("tenet_ritual_celebrations", "Moadim le-Simcha"),
    ("tenet_pursuit_of_knowledge", "Pursuit of Knowledge"),
    ("tenet_literalism", "Literalism"),
]
# A rite's identity tenet is never offered for replacement.
PROTECTED = {"tenet_talmud_torah", "tenet_baalei_hamiqra"}
# Mutually exclusive pairs (as core tenets).
RIVALS = {
    "tenet_kehillah_hokhmah": "tenet_kehillah_emunah_temimah",
    "tenet_kehillah_emunah_temimah": "tenet_kehillah_hokhmah",
    "tenet_kehillah_geonut": "tenet_kehillah_minhag_avoteinu",
    "tenet_kehillah_minhag_avoteinu": "tenet_kehillah_geonut",
    "tenet_talmud_torah": "tenet_baalei_hamiqra",
    "tenet_baalei_hamiqra": "tenet_talmud_torah",
}
ACTIONS = ["core", "permit", "ban", "lift"]


def write(rel, lines):
    p = ROOT / rel
    p.write_bytes((BOM + "\r\n".join(lines) + "\r\n").encode("utf-8"))


def triggers():
    out = HEADER + [
        "",
        "# Scope: a host whose rite is asked about $TENET$. Each is what one",
        "# action needs.",
        "kehillah_reform_can_core_trigger = {",
        "\trite ?= {",
        "\t\thas_at_least_tenet_status = { tenet = $TENET$ status = permitted }",
        "\t\tNOT = { rite_has_tenet = $TENET$ }",
        "\t}",
        "}",
        "kehillah_reform_can_permit_trigger = {",
        "\trite ?= {",
        "\t\tNOT = { has_at_least_tenet_status = { tenet = $TENET$ status = permitted } }",
        "\t\tNOT = { has_tenet_status = { tenet = $TENET$ status = prohibited } }",
        "\t}",
        "}",
        "kehillah_reform_can_ban_trigger = {",
        "\trite ?= { NOT = { has_tenet_status = { tenet = $TENET$ status = prohibited } } }",
        "\tfaith = { NOT = { any_faith_rite = { rite_has_tenet = $TENET$ } } }",
        "}",
        "kehillah_reform_can_lift_trigger = {",
        "\trite ?= { has_tenet_status = { tenet = $TENET$ status = prohibited } }",
        "}",
        "",
        "# Scope: a host. Some question of belief can be put to this gathering.",
        "kehillah_reform_any_motion_trigger = {",
        "\tOR = {",
    ]
    for key, _ in TARGETS:
        out += [f"\t\tkehillah_reform_any_action_{key}_trigger = yes"]
    out += ["\t}", "}", ""]
    for key, _ in TARGETS:
        rival = RIVALS.get(key)
        rival_line = f"\t\t\trite ?= {{ NOT = {{ rite_has_tenet = {rival} }} }}" if rival else ""
        out += [f"kehillah_reform_any_action_{key}_trigger = {{", "\tOR = {"]
        if rival_line:
            out += ["\t\tAND = {", f"\t\t\tkehillah_reform_can_core_trigger = {{ TENET = {key} }}", rival_line, "\t\t}"]
        else:
            out.append(f"\t\tkehillah_reform_can_core_trigger = {{ TENET = {key} }}")
        out += [f"\t\tkehillah_reform_can_permit_trigger = {{ TENET = {key} }}",
                f"\t\tkehillah_reform_can_ban_trigger = {{ TENET = {key} }}",
                f"\t\tkehillah_reform_can_lift_trigger = {{ TENET = {key} }}",
                "\t}", "}"]
    out += ["", "# Scope: the host, with var:kehillah_reform_tenet chosen. The action is possible."]
    for action in ACTIONS:
        out += [f"kehillah_reform_chosen_can_{action}_trigger = {{", "\tOR = {"]
        for i, (key, _) in enumerate(TARGETS, start=1):
            extra = ""
            if action == "core" and RIVALS.get(key):
                extra = f" rite ?= {{ NOT = {{ rite_has_tenet = {RIVALS[key]} }} }}"
            out.append(f"\t\tAND = {{ var:kehillah_reform_tenet ?= {i} kehillah_reform_can_{action}_trigger = {{ TENET = {key} }}{extra} }}")
        out += ["\t}", "}"]
    out += ["", "# Scope: a delegate at a sitting whose motion is a question of belief.",
            "# He favours raising, permitting or freeing a tenet he holds or has learned,",
            "# and banning one his rival tenet opposes; he opposes the reverse."]
    knows = lambda key: (f"OR = {{ has_personal_tenet = {key} "
                         f"is_target_in_variable_list = {{ name = kehillah_book_tenets target = flag:{key} }} }}")
    for side in ("favours", "opposes"):
        out += [f"kehillah_reform_delegate_{side}_trigger = {{",
                "\tinvolved_activity.var:kehillah_synod_takkanah ?= flag:tenet_reform",
                "\tOR = {"]
        for i, (key, _) in enumerate(TARGETS, start=1):
            rival = RIVALS.get(key)
            raise_cond = knows(key)
            ban_cond = f"has_personal_tenet = {rival}" if rival else "has_trait = zealous"
            if side == "opposes":
                raise_cond = f"has_personal_tenet = {rival}" if rival else "has_trait = zealous"
                ban_cond = knows(key)
            out += [
                "\t\tAND = {",
                f"\t\t\tinvolved_activity.activity_host.var:kehillah_reform_tenet ?= {i}",
                "\t\t\tOR = {",
                f"\t\t\t\tAND = {{ NOT = {{ involved_activity.activity_host.var:kehillah_reform_action ?= flag:ban }} {raise_cond} }}",
                f"\t\t\t\tAND = {{ involved_activity.activity_host.var:kehillah_reform_action ?= flag:ban {ban_cond} }}",
                "\t\t\t}",
                "\t\t}",
            ]
        out += ["\t}", "}"]
    write("common/scripted_triggers/kehillah_reform_triggers.txt", out)


def effects():
    out = HEADER + [
        "",
        "# Scope: the host (event option). Record the motion on him and on the",
        "# sitting, then put it through the synod's shared motion helper.",
        "kehillah_reform_put_motion_effect = {",
        "\tinvolved_activity ?= {",
        "\t\tset_variable = { name = kehillah_reform_tenet value = prev.var:kehillah_reform_tenet }",
        "\t}",
        "\tkehillah_synod_put_motion_effect = { MOTION = flag:tenet_reform }",
        "}",
        "",
        "# Scope: the host, at the ruling (kehillah_synod_enact_takkanah_effect).",
        "# Changes the rite's core tenets or the faith's status, refreshes every",
        "# book's ceiling in the faith, and tells the faith's players.",
        "kehillah_reform_enact_effect = {",
        "\tsave_scope_as = kehillah_reform_host",
        "\tfaith = { save_scope_as = kehillah_reform_faith }",
        "\tcustom_tooltip = kehillah_reform_enacted_tt",
        "\tif = {",
        "\t\tlimit = { var:kehillah_reform_action ?= flag:core }",
        "\t\trite ?= {",
        "\t\t\tkehillah_reform_remove_core_effect = yes",
        "\t\t\tkehillah_reform_add_core_effect = yes",
        "\t\t}",
        "\t}",
        "\telse = {",
        "\t\tscope:kehillah_reform_faith = { kehillah_reform_set_status_effect = yes }",
        "\t}",
        "\tscope:kehillah_reform_faith = {",
        "\t\tevery_faith_rite = { kehillah_standing_refresh_ceilings_rite_effect = yes }",
        "\t}",
        "\trite ?= {",
        "\t\tif = {",
        "\t\t\tlimit = { var:kehillah_reform_pending_tenet ?= prev.var:kehillah_reform_tenet }",
        "\t\t\tremove_variable = kehillah_reform_pending_tenet",
        "\t\t\tremove_variable = kehillah_reform_pending_action",
        "\t\t}",
        "\t}",
        "\tevery_player = {",
        "\t\tlimit = {",
        "\t\t\tfaith = scope:kehillah_reform_faith",
        "\t\t\tNOT = { this = scope:kehillah_reform_host }",
        "\t\t}",
        "\t\tset_variable = { name = kehillah_reform_tenet value = scope:kehillah_reform_host.var:kehillah_reform_tenet days = 60 }",
        "\t\tset_variable = { name = kehillah_reform_action value = scope:kehillah_reform_host.var:kehillah_reform_action days = 60 }",
        "\t\tif = {",
        "\t\t\tlimit = { exists = scope:kehillah_reform_host.var:kehillah_reform_replace }",
        "\t\t\tset_variable = { name = kehillah_reform_replace value = scope:kehillah_reform_host.var:kehillah_reform_replace days = 60 }",
        "\t\t}",
        "\t\tsend_interface_message = {",
        "\t\t\ttype = msg_kehillah_sefer",
        "\t\t\ttitle = kehillah_reform_msg_t",
        "\t\t\tdesc = kehillah_reform_msg_d",
        "\t\t\tleft_icon = scope:kehillah_reform_host",
        "\t\t}",
        "\t}",
        "\tdebug_log = \"kehillah_reform_enact_effect: a question of belief was settled\"",
        "}",
        "",
        "# Scope: the host's rite; reads scope:kehillah_reform_host's choice.",
        "kehillah_reform_add_core_effect = {",
    ]
    for i, (key, _) in enumerate(TARGETS, start=1):
        kw = "if" if i == 1 else "else_if"
        out.append(f"\t{kw} = {{ limit = {{ scope:kehillah_reform_host.var:kehillah_reform_tenet ?= {i} }} add_rite_tenet = {key} }}")
    out += ["}", "", "kehillah_reform_remove_core_effect = {"]
    for i, (key, _) in enumerate(REPLACEABLE, start=1):
        kw = "if" if i == 1 else "else_if"
        out.append(f"\t{kw} = {{ limit = {{ scope:kehillah_reform_host.var:kehillah_reform_replace ?= {i} rite_has_tenet = {key} }} remove_rite_tenet = {key} }}")
    out += ["}", "", "# Scope: the faith; reads scope:kehillah_reform_host's choice.",
            "kehillah_reform_set_status_effect = {"]
    status = {"permit": "permitted", "ban": "prohibited", "lift": "known"}
    first = True
    for action, st in status.items():
        for i, (key, _) in enumerate(TARGETS, start=1):
            kw = "if" if first else "else_if"
            first = False
            out.append(
                f"\t{kw} = {{ limit = {{ scope:kehillah_reform_host.var:kehillah_reform_action ?= flag:{action} "
                f"scope:kehillah_reform_host.var:kehillah_reform_tenet ?= {i} }} "
                f"set_tenet_status = {{ tenet = tenet:{key} status = {st} }} }}")
    out += ["}", "", "# Scope: a host. Clear his choice once it is settled or abandoned.",
            "kehillah_reform_clear_choice_effect = {",
            "\tremove_variable = kehillah_reform_tenet",
            "\tremove_variable = kehillah_reform_action",
            "\tremove_variable = kehillah_reform_replace",
            "}",
            "",
            "# Scope: a rite; from a Machloket's resolution ($KEY$ the disputed work).",
            "# The rite's next gathering is expected to rule on the book's first tenet:",
            "# to raise it after a victory for its defenders, to ban it after a defeat.",
            "kehillah_reform_queue_from_machloket_effect = {",
            "\tif = {",
            "\t\tlimit = { kehillah_sefer_first_tenet_$KEY$ > 0 }",
            "\t\tset_variable = { name = kehillah_reform_pending_tenet value = kehillah_sefer_first_tenet_$KEY$ years = 20 }",
            "\t\tif = {",
            "\t\t\tlimit = { var:kehillah_mk_outcome = 1 }",
            "\t\t\tset_variable = { name = kehillah_reform_pending_action value = flag:core years = 20 }",
            "\t\t}",
            "\t\telse = {",
            "\t\t\tset_variable = { name = kehillah_reform_pending_action value = flag:ban years = 20 }",
            "\t\t}",
            "\t}",
            "}"]
    write("common/scripted_effects/kehillah_reform_effects.txt", out)


def custom_loc():
    out = HEADER[:]

    def by_var(name, var, items, prefix):
        lines = [f"{name} = {{", "\ttype = character"]
        for i, _ in enumerate(items, start=1):
            lines += ["\ttext = {", f"\t\ttrigger = {{ {var} ?= {i} }}", f"\t\tlocalization_key = {prefix}{i}", "\t}"]
        lines += ["\ttext = {", "\t\tfallback = yes", "\t\tlocalization_key = KEHILLAH_REFORM_TENET_NONE", "\t}", "}"]
        return lines

    out += by_var("KehillahReformTenetName", "var:kehillah_reform_tenet", TARGETS, "KEHILLAH_REFORM_TENET_")
    out += by_var("KehillahReformReplaceName", "var:kehillah_reform_replace", REPLACEABLE, "KEHILLAH_REFORM_TENET_")
    out += by_var("KehillahReformPendingName", "rite.var:kehillah_reform_pending_tenet", TARGETS, "KEHILLAH_REFORM_TENET_")
    out += ["KehillahReformMotionText = {", "\ttype = character"]
    for action in ACTIONS:
        out += ["\ttext = {", f"\t\ttrigger = {{ var:kehillah_reform_action ?= flag:{action} }}",
                f"\t\tlocalization_key = KEHILLAH_REFORM_MOTION_{action.upper()}", "\t}"]
    out += ["\ttext = {", "\t\tfallback = yes", "\t\tlocalization_key = KEHILLAH_REFORM_MOTION_NONE", "\t}", "}"]
    write("common/customizable_localization/kehillah_reform_custom_loc.txt", out)

    loc = ["l_english:", " KEHILLAH_REFORM_TENET_NONE:0 \"a tenet\""]
    for i, (_, name) in enumerate(REPLACEABLE, start=1):
        loc.append(f" KEHILLAH_REFORM_TENET_{i}:0 \"{name}\"")
    p = ROOT / "localization/english/kehillah_reform_names_l_english.yml"
    p.write_bytes((BOM + "\n".join(loc) + "\n").encode("utf-8"))


