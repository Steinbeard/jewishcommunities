def write(path, text, bom=False):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    if not str(path).endswith('.yml'):
        depth, lines = 0, []
        for line in text.splitlines():
            code = re.sub(r'"[^"\\]*(?:\\.[^"\\]*)*"', '""', line).split('#', 1)[0]
            closing = len(code.lstrip()) - len(code.lstrip().lstrip('}'))
            lines.append('\t' * max(0, depth-closing) + line.lstrip() if line.strip() else '')
            depth += code.count('{') - code.count('}')
        assert depth == 0, path
        text = '\n'.join(lines) + '\n'
    p.write_text(text, encoding="utf-8-sig" if bom or p.suffix == ".txt" else "utf-8", newline="\n")


