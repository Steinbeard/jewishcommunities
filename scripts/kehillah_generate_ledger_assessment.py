"""Generate ledger-only sorting and assessment helpers from the live catalog.

Run independently of the full catalog generator; no standing rules are changed.
"""
import kehillah_library_catalog as catalog


def generate():
    order, works = catalog.load()
    root = catalog.ROOT
    out = ["# GENERATED by scripts/kehillah_generate_ledger_assessment.py",
           "# Player scope. Partition the existing dated catalog into rank buckets.",
           "# Each included book's rank is evaluated once, only on a ledger rebuild.",
           "kehillah_ledger_sort_rank_effect = {"]
    for rank in range(12):
        out.append(f"\tclear_variable_list = kehillah_ledger_rank_{rank}")
    for flag in catalog.ledger_order(order, works):
        out += ["\tif = {", f"\t\tlimit = {{ is_target_in_variable_list = {{ name = kehillah_lib_catalog_works target = flag:{flag} }} }}",
                f"\t\tset_variable = {{ name = kehillah_ledger_rank value = var:kehillah_ledger_rite.kehillah_lib_rite_standing_{flag} }}",
                "\t\tswitch = {", "\t\t\ttrigger = var:kehillah_ledger_rank"]
        for rank in range(12):
            out.append(f"\t\t\t{rank} = {{ add_to_variable_list = {{ name = kehillah_ledger_rank_{rank} target = flag:{flag} }} }}")
        out += ["\t\t}", "\t}"]
    out.append("\tclear_variable_list = kehillah_lib_catalog_works")
    for rank in reversed(range(12)):
        out += ["\tevery_in_list = {", f"\t\tvariable = kehillah_ledger_rank_{rank}",
                "\t\troot = { add_to_variable_list = { name = kehillah_lib_catalog_works target = prev } }", "\t}",
                f"\tclear_variable_list = kehillah_ledger_rank_{rank}"]
    out += ["\tremove_variable = kehillah_ledger_rank", "}"]
    catalog.write(root / "common/scripted_effects/kehillah_ledger_rank_effects.txt", out)

    tenets = sorted({t for w in works.values() for k in ('argues_for', 'argues_against') for t in w.get(k, [])})
    values = ["# GENERATED by scripts/kehillah_generate_ledger_assessment.py", "# Rite scope: the status actually used by the ceiling calculation."]
    for flag in order:
        canonical = bool(works[flag].get('canon'))
        values += [f"kehillah_ledger_doctrinal_{flag} = {{ value = {int(canonical)} }}",
                   f"kehillah_ledger_ceiling_{flag} = {{ value = kehillah_lib_{'rite_standing' if canonical else 'ceiling'}_{flag} }}"]
    for tenet in tenets:
        values += [f"kehillah_ledger_status_{tenet} = {{", "\tvalue = 0",
                   f"\tif = {{ limit = {{ has_tenet_status = {{ tenet = {tenet} status = prohibited }} }} value = 1 }}",
                   f"\telse_if = {{ limit = {{ rite_has_tenet = {tenet} }} value = 4 }}",
                   f"\telse_if = {{ limit = {{ has_at_least_tenet_status = {{ tenet = {tenet} status = permitted }} }} value = 3 }}",
                   f"\telse_if = {{ limit = {{ has_at_least_tenet_status = {{ tenet = {tenet} status = known }} }} value = 2 }}", "}"]
    catalog.write(root / "common/script_values/kehillah_ledger_assessment_values.txt", values)

    loc = ["l_english:"]
    rite = "GetPlayer.MakeScope.Var('kehillah_ledger_rite')"
    for flag in order:
        w = works[flag]
        text = "$KEHILLAH_LEDGER_ASSESSMENT_INTRO$"
        if w.get('canon'):
            text += r"\n\n$KEHILLAH_LEDGER_DOCTRINAL$"
        else:
            baseline = f"{rite}.ScriptValue('kehillah_lib_baseline_{flag}')"
            text += r"\n\n$KEHILLAH_LEDGER_BASELINE$ " + f"[Localize(Concatenate('KEHILLAH_STANDING_FMT_', IntToString(FixedPointToInt({baseline}))))]"
            for key, label in (('argues_for', 'SUPPORTS'), ('argues_against', 'OPPOSES')):
                for tenet in w.get(key, []):
                    status = f"{rite}.ScriptValue('kehillah_ledger_status_{tenet}')"
                    text += rf"\n$KEHILLAH_LEDGER_{label}$ ${tenet}_name$: " + f"[Localize(Concatenate('KEHILLAH_LEDGER_{label}_STATUS_', IntToString(FixedPointToInt({status}))))]"
            if catalog.authored(w):
                text += r"\n$KEHILLAH_LEDGER_AUTHORED$"
            text += r"\n\n$KEHILLAH_LEDGER_LIMIT_RULES$\n\n$KEHILLAH_LEDGER_RECEPTION_RULES$"
        loc.append(f' kehillah_ledger_assessment_{flag}:0 "{text}"')
    catalog.write(root / "localization/english/kehillah_ledger_assessment_generated_l_english.yml", loc)


if __name__ == '__main__':
    generate()
