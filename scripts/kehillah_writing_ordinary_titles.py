"""Keep ordinary manuscript, completion and news titles tied to the chosen form."""

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CUSTOM = ROOT / "common/customizable_localization/kehillah_writing_ordinary_titles_custom_loc.txt"
LOC = ROOT / "localization/english/kehillah_writing_ordinary_titles_l_english.yml"
EFFECT = ROOT / "common/scripted_effects/kehillah_writing_ordinary_titles_generated_effects.txt"

TITLES = {
    "torah": "A Running Commentary on the Torah",
    "midrash": "Expansions of the Midrash",
    "poetry": "Songs of Scripture",
    "grammar": "A Grammar of Scripture",
    "chronicle": "Records of Our Communities",
    "talmud": "Glosses on the Bavli",
    "yerushalmi": "Glosses on the Yerushalmi",
    "law": "A Book of Practical Law",
    "responsa": "Answers to Distant Questions",
    "minhag": "The Customs of Our Community",
    "siddur": "An Order of Prayer",
    "tradition_history": "The Chain of the Sages",
    "scriptural_law": "Commandments from Scripture",
    "dialogue": "A Dialogue on Scripture and Revelation",
    "systematic_dialogue": "A Dialogue on Faith and Reason",
    "mystical": "The Hidden Pattern of Creation",
    "disputation": "In Defense of Our Tradition",
    "translation": "A Gloss on the Philosophers",
    "ethics": "Counsel for a Righteous Life",
    "devotion": "The Duties Within",
}


def main() -> None:
    events = (ROOT / "events/kehillah_writing_events.txt").read_text(encoding="utf-8")
    forms = set(re.findall(r"kehillah_writing_choose_project_effect = \{ FORM = (\w+) GENRE = \w+ \}", events))
    assert forms == set(TITLES), f"unmapped writing forms: {sorted(forms ^ set(TITLES))}"
    custom = ["# Generated by scripts/kehillah_writing_ordinary_titles.py."]
    custom += ["KehillahWritingOrdinaryTitle = {", "\ttype = character"]
    for form in TITLES:
        custom += [f"\ttext = {{ trigger = {{ var:kehillah_writing_ordinary_form ?= flag:{form} }} localization_key = kehillah_writing_ordinary_title_{form} }}"]
    custom += ["\ttext = { trigger = { always = no } localization_key = kehillah_writing_unknown_manuscript fallback = yes }", "}"]
    CUSTOM.write_text("\n".join(custom) + "\n", encoding="utf-8-sig")
    loc = ["l_english:"] + [f' kehillah_writing_ordinary_title_{form}:0 "{title}"' for form, title in TITLES.items()]
    loc += [f' kehillah_writing_ordinary_desc_{form}:0 "An original manuscript of {title}. Scholars nearby have heard of it, but it has not become an enduring work of the Sefarim Ledger."' for form, title in TITLES.items()]
    LOC.write_text("\n".join(loc) + "\n", encoding="utf-8-sig")
    effect = ["# Generated by scripts/kehillah_writing_ordinary_titles.py.",
              "# Scope: the newly created artifact. Read the author's form, then set stable text.",
              "kehillah_writing_set_ordinary_artifact_identity_effect = {"]
    for index, form in enumerate(TITLES):
        effect += [f"\t{'if' if index == 0 else 'else_if'} = {{",
                   f"\t\tlimit = {{ root = {{ var:kehillah_writing_ordinary_form ?= flag:{form} }} }}",
                   f"\t\tset_artifact_name = kehillah_writing_ordinary_title_{form}",
                   f"\t\tset_artifact_description = kehillah_writing_ordinary_desc_{form}", "\t}"]
    effect.append("}")
    EFFECT.write_text("\n".join(effect) + "\n", encoding="utf-8-sig")


if __name__ == "__main__":
    main()
