"""Build doctrine-aware holiday scheduling and non-Rabbinic scene variants.

Run after editing the original thirteen scenes. Their effects are shared, but
the variants' complete text is authored in jewish_holiday_variants_l_english.yml.
No religious calendar dates or newly researched observances are introduced.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SCENES = {
    1: ("seventh_month", (8, 9, 10)), 2: ("seventh_month", (8, 9, 10)),
    3: ("passover", (3, 4, 5)), 4: ("passover", (3, 4, 5)),
    5: ("hanukkah", (11, 12, 1)), 6: ("hanukkah", (11, 12, 1)),
    7: ("purim", (2, 3, 4)), 8: ("purim", (2, 3, 4)),
    9: ("atonement", (8, 9, 10)), 10: ("atonement", (8, 9, 10)),
    11: ("booths", (8, 9, 10)), 12: ("booths", (8, 9, 10)),
    13: ("weeks", (5, 6, 7)),
}


def block(text, key):
    start = re.search(r"(?m)^" + re.escape(key) + r" = \{", text).start()
    # Ignore braces in comments and quoted strings (including escaped quotes).
    tokens = re.finditer(r'#[^\n]*|"(?:\\.|[^"\\])*"|[{}]', text[start:])
    depth = 0
    for token in tokens:
        if token[0] == "{": depth += 1
        elif token[0] == "}":
            depth -= 1
            if depth == 0: return text[start:start + token.end()]
    raise ValueError(key)


def write(path, text):
    (ROOT / path).write_text(text.rstrip() + "\n", encoding="utf-8-sig", newline="\r\n")


def build():
    source = (ROOT / "events/jewish_holiday_events.txt").read_text(encoding="utf-8-sig")
    # All originals are Rabbinic-practice scenes; the yearly draw selects an
    # occasion first, and display selects the appropriate practice variant.
    for n in SCENES:
        key = f"jewish_holidays.{n:04d}"
        old = block(source, key)
        new = old.replace("\ttrigger = {", "\ttrigger = {\n\t\tjewish_holiday_uses_rabbinic_customs_trigger = yes", 1)
        if "jewish_holiday_uses_rabbinic_customs_trigger" not in old:
            source = source.replace(old, new)
    # Replace the hidden queue definitions, keeping stable console IDs.
    for n in SCENES:
        key = f"jewish_holidays.{100+n:04d}"
        source = source.replace(block(source, key), f"""{key} = {{
    type = character_event
    hidden = yes
    trigger = {{
        jewish_holiday_scene_{n:04d}_eligible_trigger = yes
        jewish_holiday_no_pending_trigger = yes
    }}
    immediate = {{
        add_character_flag = jewish_holiday_{n:04d}_pending
        add_character_flag = jewish_holiday_calendar_running
        trigger_event = {{ on_action = jewish_holiday_calendar_pulse months = 1 }}
    }}
}}""")
    write("events/jewish_holiday_events.txt", source)

    triggers = ["# GENERATED by scripts/kehillah_holiday_revision_build.py.",
                "# Character scope. Canon and observance are independent of personal tenets.",
                "jewish_holiday_uses_rabbinic_customs_trigger = { is_rabbinic_authority_jewish_trigger = yes }",
                "jewish_holiday_uses_rabbinic_seder_trigger = { jewish_holiday_uses_rabbinic_customs_trigger = yes }",
                "jewish_holiday_uses_rabbinic_purim_trigger = { jewish_holiday_uses_rabbinic_customs_trigger = yes }",
                "jewish_holiday_accepts_esther_trigger = { is_hebrew_canon_jewish_trigger = yes }"]
    for occasion in dict.fromkeys(x[0] for x in SCENES.values()):
        cap = {"hanukkah": "is_rabbinic_authority_jewish_trigger", "purim": "jewish_holiday_accepts_esther_trigger"}.get(occasion, "is_jewish_character_trigger")
        triggers.append(f"jewish_holiday_observes_{occasion}_trigger = {{ {cap} = yes }}")
    triggers.append("jewish_holiday_no_pending_trigger = {\n    NOR = {\n" + "\n".join(f"        has_character_flag = jewish_holiday_{n:04d}_pending" for n in SCENES) + "\n    }\n}")
    for n, (occasion, _) in SCENES.items():
        people = ""
        if n == 3:
            people = "\n    any_child = { is_adult = no }"
        elif n in (9, 12):
            people = "\n    any_courtier = { is_jewish_character_trigger = yes is_adult = yes is_imprisoned = no }"
        triggers.append(f"jewish_holiday_scene_{n:04d}_eligible_trigger = {{\n    jewish_holiday_observes_{occasion}_trigger = yes\n    is_alive = yes\n    is_adult = yes\n    is_imprisoned = no{people}\n}}")
    write("common/scripted_triggers/kehillah_holiday_capability_triggers.txt", "\n\n".join(triggers))

    variants = ["# GENERATED from the original scenes; all text is separately authored.", "namespace = jewish_holidays"]
    for n in SCENES:
        if n in (5, 6): continue
        original = block(source, f"jewish_holidays.{n:04d}")
        variant = original.replace(f"jewish_holidays.{n:04d}", f"jewish_holidays.{200+n:04d}")
        # The event may be fired directly, after a conversion, or by the queue.
        trigger = re.search(r"\n\ttrigger = \{", variant)
        tail = variant[trigger.start()+1:]
        old_trigger = block(tail.replace("\ttrigger", "trigger", 1), "trigger")
        # block's result loses only the leading tab on the first line.
        preserved = old_trigger.replace("jewish_holiday_uses_rabbinic_customs_trigger = yes", "NOT = { jewish_holiday_uses_rabbinic_customs_trigger = yes }")
        preserved = preserved.replace("trigger = {", f"trigger = {{\n\t\tjewish_holiday_scene_{n:04d}_eligible_trigger = yes", 1)
        variant = variant.replace("\t" + old_trigger, "\t" + preserved, 1)
        if n == 3:
            variant = variant.replace("desc = jewish_holidays.0203.desc", "desc = { first_valid = { triggered_desc = { trigger = { rite = { kehillah_rite_samaritan_trigger = yes } } desc = jewish_holidays.0203.samaritan_desc } desc = jewish_holidays.0203.desc } }")
        variants.append(variant)
    write("events/kehillah_holiday_variant_events.txt", "\n\n".join(variants))

    # A direct random_list filters entries before the draw. This preserves the
    # same 60/75% player and 12/16% AI chance for all traditions.
    actions = """# GENERATED by scripts/kehillah_holiday_revision_build.py.
# Everyone includes courtiers. Using only this engine hook avoids giving
# rulers a second annual draw. A queued scene has one monthly callback.
random_yearly_everyone_pulse = { on_actions = { jewish_holiday_resume_pending_pulse jewish_holiday_yearly_pulse } }
jewish_holiday_resume_pending_pulse = {
    trigger = {
        NOT = { jewish_holiday_no_pending_trigger = yes }
        NOT = { has_character_flag = jewish_holiday_calendar_running }
    }
    effect = {
        add_character_flag = jewish_holiday_calendar_running
        trigger_event = { on_action = jewish_holiday_calendar_pulse months = 1 }
    }
}

jewish_holiday_yearly_pulse = {
    trigger = {
        is_jewish_character_trigger = yes
        is_adult = yes
        is_imprisoned = no
        jewish_holiday_no_pending_trigger = yes
    }
    effect = {
        random = {
            chance = {
                value = 12
                if = { limit = { is_ai = no } value = 60 }
                if = {
                    limit = {
                        OR = {
                            rite = { rite_has_tenet = tenet_ritual_celebrations }
                            has_personal_tenet = tenet_ritual_celebrations
                        }
                    }
                    value = 16
                    if = { limit = { is_ai = no } value = 75 }
                }
            }
            random_list = {
"""
    for n in SCENES:
        actions += f"                20 = {{ trigger = {{ jewish_holiday_scene_{n:04d}_eligible_trigger = yes }} trigger_event = jewish_holidays.{100+n:04d} }}\n"
    actions += """            }
        }
    }
}

jewish_holiday_calendar_pulse = {
    # Deliberately no faith trigger: converted characters must lose old queues.
    effect = {
"""
    for n, (_, months) in SCENES.items():
        actions += f"""        if = {{
            limit = {{ has_character_flag = jewish_holiday_{n:04d}_pending }}
            if = {{
                limit = {{ NOT = {{ jewish_holiday_scene_{n:04d}_eligible_trigger = yes }} }}
                remove_character_flag = jewish_holiday_{n:04d}_pending
            }}
            else_if = {{
                limit = {{ OR = {{ {' '.join(f'current_month = {m}' for m in months)} }} }}
                remove_character_flag = jewish_holiday_{n:04d}_pending
"""
        if n in (5,6): actions += f"                trigger_event = jewish_holidays.{n:04d}\n"
        else: actions += f"""                if = {{
                    limit = {{ jewish_holiday_uses_rabbinic_customs_trigger = yes }}
                    trigger_event = jewish_holidays.{n:04d}
                }}
                else = {{ trigger_event = jewish_holidays.{200+n:04d} }}
"""
        actions += "            }\n        }\n"
    actions += """        if = {
            limit = { NOT = { jewish_holiday_no_pending_trigger = yes } }
            trigger_event = { on_action = jewish_holiday_calendar_pulse months = 1 }
        }
        else = { remove_character_flag = jewish_holiday_calendar_running }
    }
}
"""
    write("common/on_action/jewish_holiday_on_actions.txt", actions)


if __name__ == "__main__":
    build()
