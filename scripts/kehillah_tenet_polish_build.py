"""Build one-time solidarity migration and starting-tenet familiarity.

Faith status and personal knowledge are different 1.20 systems. History owns
new-game statuses; this generator seeds familiarity only with teachings whose
faith status is already defined, never with the entire vanilla tenet database.
"""
from pathlib import Path
from kehillah_faith_revision_build import KNOWN, PERMITTED, PROHIBITED, COVENANT

ROOT = Path(__file__).resolve().parents[1]
VERSION = "kehillah_tenet_polish_20261115_revival"


def write(path, lines):
    text = "\n".join(lines) if isinstance(lines, list) else lines
    (ROOT / path).write_text(text.rstrip() + "\n", encoding="utf-8-sig", newline="\r\n")


def build():
    out = ["# GENERATED by scripts/kehillah_tenet_polish_build.py.",
           "# Fresh games use history. Existing saves add missing statuses once.",
           "kehillah_tenet_polish_migrate_effect = {", "    if = {",
           f"        limit = {{ NOT = {{ has_global_variable = {VERSION} }} }}",
           f"        set_global_variable = {{ name = {VERSION} value = yes }}"]
    for faith in KNOWN:
        out += [f"        faith:{faith} ?= {{", "            kehillah_sefer_quiet_rite_messages_effect = yes"]
        for status, values in (("known", KNOWN[faith]), ("permitted", PERMITTED[faith]), ("prohibited", PROHIBITED[faith])):
            for tenet in dict.fromkeys(values):
                out += ["            if = {",
                        f"                limit = {{ main_rite = {{ has_tenet_status = {{ tenet = {tenet} status = unknown }} }} }}",
                        f"                set_tenet_status = {{ tenet = tenet:{tenet} status = {status} }}", "            }"]
        out += ["        }"]
    for old, new in (("tenet_kehillah_geonut", "tenet_religious_legal_pronouncements"),
                     ("tenet_kehillah_pilpul", "tenet_kehillah_scholarly_study"),
                     ("tenet_kehillah_minhag_avoteinu", COVENANT)):
        out += ["        religion:judaism_religion = { every_faith = { every_faith_rite = {",
                f"            if = {{ limit = {{ rite_has_tenet = {old} }}",
                f"                remove_rite_tenet = {old}",
                f"                if = {{ limit = {{ NOT = {{ rite_has_tenet = {new} }} }} add_rite_tenet = {new} }}"]
        for fallback in ("tenet_kehillah_scholarly_study", COVENANT, "tenet_literalism", "tenet_adaptive"):
            if fallback != new:
                out += [f"                else_if = {{ limit = {{ NOT = {{ rite_has_tenet = {fallback} }} }} add_rite_tenet = {fallback} }}"]
        out += ["            }", "        } } }"]
    out += ["        religion:judaism_religion = {", "            every_faith = {",
            "                kehillah_sefer_quiet_rite_messages_effect = yes",
            "                if = {",
            f"                    limit = {{ main_rite = {{ has_tenet_status = {{ tenet = {COVENANT} status = unknown }} }} }}",
            f"                    set_tenet_status = {{ tenet = tenet:{COVENANT} status = permitted }}",
            "                }",
            "                every_faith_rite = {",

            "                    if = {",
            "                        limit = { rite_has_tenet = tenet_communal_identity }",
            "                        remove_rite_tenet = tenet_communal_identity", "                        if = {",
            f"                            limit = {{ NOT = {{ rite_has_tenet = {COVENANT} }} }}",
            f"                            add_rite_tenet = {COVENANT}", "                        }",
            "                        else_if = {", "                            limit = { NOT = { rite_has_tenet = tenet_adaptive } }",
            "                            add_rite_tenet = tenet_adaptive", "                        }",
            "                        else = { add_rite_tenet = tenet_literalism }", "                    }",
            """                    if = {
                        limit = { this = rite:samaritan rite_has_tenet = tenet_kehillah_covenant_community rite_has_tenet = tenet_literalism rite_has_tenet = tenet_ritual_celebrations }
                        remove_rite_tenet = tenet_ritual_celebrations
                        add_rite_tenet = tenet_kehillah_temple_service
                    }
                    # Replace only the previous exact Ashkenaz default.
                    if = {
                        limit = {
                            this = rite:minhag_ashkenaz
                            rite_has_tenet = tenet_asceticism
                            rite_has_tenet = tenet_legalism
                            rite_has_tenet = tenet_kehillah_covenant_community
                        }
                        remove_rite_tenet = tenet_legalism
                        add_rite_tenet = tenet_kehillah_scholarly_study
                    }""",
            "                    kehillah_standing_refresh_ceilings_rite_effect = yes",
            "                }", "            }", "        }",
            "        if = {",
            "            limit = { NOR = { has_global_variable = kehillah_tenet_polish_20261115 has_global_variable = kehillah_tenet_polish_20261115_study } }",
            "            religion:judaism_religion = { every_faith = {",
            "                kehillah_sefer_quiet_rite_messages_effect = yes",
            "                set_tenet_status = { tenet = tenet:tenet_communal_identity status = unknown }",
            "                set_tenet_status = { tenet = tenet:tenet_gnosticism status = prohibited }",
            "            } }",
            "        }",
            "        every_living_character = {", "            if = {",
            "                limit = { is_jewish_character_trigger = yes }",
            "                kehillah_faith_revision_personal_effect = yes",
            "                if = {", "                    limit = { has_personal_tenet = tenet_communal_identity }",
            "                    remove_personal_tenet = tenet_communal_identity", "                    if = {",
            f"                        limit = {{ NOT = {{ has_personal_tenet = {COVENANT} }} }}",
            f"                        force_set_personal_tenet = {COVENANT}", "                    }", "                }",
            "                remove_variable = kehillah_tenet_familiarity_faith",
            "                kehillah_tenet_starting_familiarity_effect = yes",
            "            }", "        }", "    }", "}",
            "", "# Character scope. Learning that a teaching exists does not endorse it.",
            "kehillah_tenet_starting_familiarity_effect = {", "    if = {",
            "        limit = {", "            is_playable_character = yes", "            is_jewish_character_trigger = yes",
            "            NOT = { var:kehillah_tenet_familiarity_faith ?= faith }", "        }",
            "        set_variable = { name = kehillah_tenet_familiarity_faith value = faith }"]
    tenets = sorted(set(t for matrix in (KNOWN, PERMITTED, PROHIBITED) for values in matrix.values() for t in values))
    for tenet in tenets:
        out += ["        if = {", "            limit = {", f"                NOT = {{ knows_tenet = {tenet} }}",
                "                OR = {",
                f"                    rite = {{ NOT = {{ has_tenet_status = {{ tenet = {tenet} status = unknown }} }} }}",
                f"                    faith.main_rite = {{ rite_has_tenet = {tenet} }}",
                "                }", "            }", f"            add_known_tenet = {tenet}", "        }"]
    out += ["    }", "}"]
    write("common/scripted_effects/kehillah_tenet_polish_effects.txt", out)
    write("common/on_action/kehillah_tenet_polish_on_actions.txt", f"""# GENERATED. Historical status data is not changed at new-game startup.
on_game_start_after_lobby = {{ on_actions = {{ kehillah_tenet_polish_new_game }} }}
kehillah_tenet_polish_new_game = {{
    effect = {{
        set_global_variable = {{ name = {VERSION} value = yes }}
        every_living_character = {{
            limit = {{ is_playable_character = yes is_jewish_character_trigger = yes }}
            kehillah_tenet_starting_familiarity_effect = yes
            # A harmless second check after all after-lobby assignments finish.
            trigger_event = {{ id = kehillah_tenet_polish_debug.0003 days = 1 }}
        }}
    }}
}}
yearly_global_pulse = {{ on_actions = {{ kehillah_tenet_polish_yearly }} }}
kehillah_tenet_polish_yearly = {{ effect = {{ kehillah_tenet_polish_migrate_effect = yes }} }}
yearly_playable_pulse = {{ on_actions = {{ kehillah_tenet_polish_character }} }}
on_faith_conversion = {{ on_actions = {{ kehillah_tenet_polish_character }} }}
on_title_gain = {{ on_actions = {{ kehillah_tenet_polish_character }} }}
kehillah_tenet_polish_character = {{ effect = {{ kehillah_tenet_starting_familiarity_effect = yes }} }}
""")
    probe = ["# GENERATED. Console audit (.1), one-time old-save repair (.2), familiarity (.3).",
             "namespace = kehillah_tenet_polish_debug", "kehillah_tenet_polish_debug.0001 = {",
             "    type = character_event", "    hidden = yes", "    immediate = {"]
    for tenet in ("tenet_kehillah_hokhmah", "tenet_kehillah_scholarly_study", "tenet_kehillah_sacred_liturgy", COVENANT, "tenet_adaptive", "tenet_human_sacrifice", "tenet_communal_identity", "tenet_gnosticism"):
        probe += [f'        if = {{ limit = {{ knows_tenet = {tenet} }} debug_log = "TENET_POLISH {tenet}: character knows=yes" }}',
                  f'        else = {{ debug_log = "TENET_POLISH {tenet}: character knows=no" }}']
        for status in ("core", "known", "permitted", "prohibited", "unknown"):
            probe += [f'        if = {{ limit = {{ rite = {{ has_tenet_status = {{ tenet = {tenet} status = {status} }} }} }} debug_log = "TENET_POLISH {tenet}: selected rite={status}" }}']
    probe += ["    }", "}", "kehillah_tenet_polish_debug.0002 = {", "    type = character_event hidden = yes",
              '    immediate = { kehillah_tenet_polish_migrate_effect = yes debug_log = "TENET_POLISH: versioned repair checked" }', "}",
              "kehillah_tenet_polish_debug.0003 = {", "    type = character_event hidden = yes",
              "    immediate = { kehillah_tenet_starting_familiarity_effect = yes }", "}"]
    write("events/kehillah_tenet_polish_debug_events.txt", probe)


if __name__ == "__main__":
    build()
